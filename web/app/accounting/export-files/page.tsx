"use client";

import { useState, useEffect, useCallback } from "react";
import { useRouter } from "next/navigation";
import { Plus, Download, Eye } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { DataTable, Column } from "@/components/ui/data-table";
import { useOrgBranch } from "@/lib/org-branch-context";
import { fetchExportFiles, type AccountingExportFile } from "@/lib/api/accounting";
import { ExportStatusBadge, providerLabel, fmtDate, fmtDatetime } from "../_utils";

export default function ExportFilesPage() {
  const router = useRouter();
  const { token, orgId } = useOrgBranch();

  const [files, setFiles]       = useState<AccountingExportFile[]>([]);
  const [loading, setLoading]   = useState(true);
  const [page, setPage]         = useState(1);
  const [totalPages, setTotalPages] = useState(1);
  const [totalCount, setTotalCount] = useState(0);

  const load = useCallback(async () => {
    if (!token || !orgId) return;
    setLoading(true);
    try {
      const res = await fetchExportFiles({ page }, token, orgId);
      setFiles(res.data);
      setTotalPages(res.meta?.total_pages ?? 1);
      setTotalCount(res.meta?.total_count ?? 0);
    } catch { /* silent */ }
    finally { setLoading(false); }
  }, [token, orgId, page]);

  useEffect(() => { load(); }, [load]);

  const columns: Column<AccountingExportFile>[] = [
    {
      key: "created_at",
      header: "Created",
      render: (_, row) => (
        <span className="text-xs text-text-secondary whitespace-nowrap">{fmtDatetime(row.created_at)}</span>
      ),
    },
    {
      key: "provider",
      header: "Provider",
      render: (_, row) => <span className="text-sm font-medium">{providerLabel(row.provider)}</span>,
    },
    {
      key: "export_type",
      header: "Export Type",
      render: (_, row) => (
        <span className="text-sm capitalize">{row.export_type.replace(/_/g, " ")}</span>
      ),
    },
    {
      key: "date_from",
      header: "Date Range",
      render: (_, row) => (
        <span className="text-xs text-text-secondary whitespace-nowrap">
          {row.date_from ? `${fmtDate(row.date_from)} – ${fmtDate(row.date_to)}` : "All dates"}
        </span>
      ),
    },
    {
      key: "branch",
      header: "Branch",
      render: (_, row) => (
        <span className="text-sm text-text-secondary">{row.branch?.name ?? "All branches"}</span>
      ),
    },
    {
      key: "status",
      header: "Status",
      render: (_, row) => <ExportStatusBadge status={row.status} />,
    },
    {
      key: "generated_by",
      header: "Generated By",
      render: (_, row) => (
        <span className="text-xs text-text-secondary">
          {row.generated_by
            ? `${row.generated_by.first_name} ${row.generated_by.last_name}`.trim() || row.generated_by.email
            : "—"}
        </span>
      ),
    },
    {
      key: "actions",
      header: "",
      render: (_, row) => (
        <div className="flex gap-1">
          <Button
            size="sm"
            variant="ghost"
            onClick={(e) => { e.stopPropagation(); router.push(`/accounting/export-files/${row.id}`); }}
            title="View"
          >
            <Eye className="h-3.5 w-3.5" />
          </Button>
          {row.downloadable && (
            <Button
              size="sm"
              variant="ghost"
              onClick={(e) => { e.stopPropagation(); router.push(`/accounting/export-files/${row.id}?download=1`); }}
              title="Download"
              className="text-primary"
            >
              <Download className="h-3.5 w-3.5" />
            </Button>
          )}
        </div>
      ),
    },
  ];

  return (
    <div>
      {/* ── Header actions ── */}
      <div className="flex justify-end mb-4">
        <Button onClick={() => router.push("/accounting/export-files/new")}>
          <Plus className="mr-2 h-4 w-4" />
          New Export
        </Button>
      </div>

      {/* ── Table ── */}
      <DataTable
        columns={columns}
        data={files}
        isLoading={loading}
        emptyMessage="No exports yet. Create your first batch export."
        emptyContent={
          <div className="flex flex-col items-center py-12 gap-3">
            <div className="flex h-12 w-12 items-center justify-center rounded-full bg-primary/10">
              <Download className="h-6 w-6 text-primary" />
            </div>
            <p className="text-sm text-text-secondary">No exports yet.</p>
            <Button size="sm" onClick={() => router.push("/accounting/export-files/new")}>
              <Plus className="mr-1.5 h-3.5 w-3.5" />
              Create Export
            </Button>
          </div>
        }
        onRowClick={(row) => router.push(`/accounting/export-files/${row.id}`)}
        rowClassName={(row) => row.status === "failed" ? "bg-red-50/30" : undefined}
      />

      {/* ── Pagination ── */}
      {!loading && totalPages > 1 && (
        <div className="flex items-center justify-between mt-4 text-sm text-text-secondary">
          <span>{totalCount} exports total</span>
          <div className="flex gap-2">
            <Button size="sm" variant="outline" disabled={page <= 1} onClick={() => setPage((p) => p - 1)}>
              Previous
            </Button>
            <span className="flex items-center px-2">{page} / {totalPages}</span>
            <Button size="sm" variant="outline" disabled={page >= totalPages} onClick={() => setPage((p) => p + 1)}>
              Next
            </Button>
          </div>
        </div>
      )}
    </div>
  );
}
